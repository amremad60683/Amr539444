  S(this.lang, [this.gender = 'm']);

  final String lang;
  final String gender;
  bool get isAr => lang == 'ar';
  bool get isFemale => gender == 'f';

  String t(String key, [Map<String, Object?> args = const {}]) {
    String? v;
    if (isAr) {
      if (isFemale) v = _arF[key];
      v ??= _ar[key];
    } else {
      v = _en[key];
    }
    v ??= _en[key] ?? key;
    args.forEach((k, val) => v = v!.replaceAll('{$k}', '$val'));
    return v!;
  }

  String get currency => isAr ? 'ج.م' : 'EGP';

  static final _num = NumberFormat('#,##0.##', 'en');

  String money(num v) => '${_num.format(v)} $currency';
  String num0(num v) => _num.format(v);

  /// Dates use Western digits everywhere, like the amounts.
  static String _latin(String v) {
    const ar = '٠١٢٣٤٥٦٧٨٩';
    for (var i = 0; i < 10; i++) {
      v = v.replaceAll(ar[i], '$i');
    }
    return v.replaceAll('\u200f', '');
  }

  String _fmt(DateFormat f, DateTime d) => _latin(f.format(d));
  String get _loc => isAr ? 'ar' : 'en';

  String date(DateTime d) => _fmt(DateFormat.yMMMEd(_loc), d);
  String dayMonth(DateTime d) => _fmt(DateFormat.MMMMd(_loc), d);
  String shortDate(DateTime d) => _fmt(DateFormat.MMMd(_loc), d);
  String weekday(DateTime d) => _fmt(DateFormat.E(_loc), d);
  String weekdayLong(DateTime d) => _fmt(DateFormat.EEEE(_loc), d);
  String time(DateTime d) => _fmt(DateFormat.jm(_loc), d);

